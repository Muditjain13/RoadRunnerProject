-- Monthly RANGE COLUMNS partitioning on created_at, applied after the
-- table is seeded at volume so the 000003 migration's unpartitioned
-- state is the honest "before" for docs/perf/ - see
-- docs/perf/booking-events-partitioning.md for before/after EXPLAIN
